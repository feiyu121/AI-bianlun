// 辩题库。选题标准有三条，缺一个这场就没法看：
// 1. 两边都有话说，不能一边天然正确（否则模型会集体倒向「正确」那侧，变成互相点头）；
// 2. 落点在打工日常，不碰社会议题——SAFETY_PROMPT 是按「单主播闲聊」写的，扛不住舆论题；
// 3. 立场能用一句具体的、可以被打断的话讲清楚，不能是「如何看待……」这种论文题。
//
// 每位辩手三条「不可让步的前提」是硬约束：模型最容易的塌方是第三句就开始和稀泥，
