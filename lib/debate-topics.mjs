export function topicById(id) {
  return DEBATE_TOPICS.find(topic => topic.id === id) || null;
}

// exclude 可以是单个 id，也可以是 id 数组。连播时传最近几场，避免刚打完的辩题
// 过两场又出现——观众会以为卡了重播。池子只有 8 题，排除 3 场仍剩下 5 题可选。
export function pickTopic(rng = Math.random, exclude = '') {
  const skip = new Set(Array.isArray(exclude) ? exclude : [exclude].filter(Boolean));
  const pool = DEBATE_TOPICS.filter(topic => !skip.has(topic.id));
  return pool[Math.floor(rng() * pool.length)] || DEBATE_TOPICS[0];
}
